#!/usr/bin/env bash
# Pre-generate the cluster CAs, service-account key and bootstrap token so every
# node can bootstrap from Ignition alone (nothing is copied between nodes).
# Output (treat both like passwords):
#   secrets/00_base-k8s-token.yaml  join token + CA hash, for every node
#   secrets/00_base-k8s-pki.yaml    CA/SA keys, for control plane nodes only
# Both are Butane layers like the ones in butane/, kept apart from them so
# that nothing secret sits in a tracked directory.

set -euo pipefail

cd "$(dirname "$0")/.."

secrets_dir="secrets"
cert_dir="$secrets_dir/certs"
token_yaml="$secrets_dir/00_base-k8s-token.yaml"
pki_yaml="$secrets_dir/00_base-k8s-pki.yaml"
days=3650

if [[ ( -e $token_yaml || -e $pki_yaml ) && ${FORCE:-0} != 1 ]]; then
  echo "$token_yaml or $pki_yaml already exists; refusing to overwrite the cluster secrets (FORCE=1 to regenerate)" >&2
  exit 1
fi

umask 077
mkdir -p "$secrets_dir"
rm -rf "$cert_dir"
mkdir -p "$cert_dir"

# kubeadm token format: [a-z0-9]{6}.[a-z0-9]{16}
rand() { LC_ALL=C tr -dc 'a-z0-9' < /dev/urandom | head -c "$1" || true; }
token="$(rand 6).$(rand 16)"

ca() {
  openssl req -x509 -newkey rsa:2048 -nodes -days "$days" -subj "/CN=$2" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,digitalSignature,keyEncipherment,keyCertSign" \
    -keyout "$cert_dir/$1.key" -out "$cert_dir/$1.crt" 2>/dev/null
}

ca ca kubernetes
ca front-proxy-ca front-proxy-ca
ca etcd-ca etcd-ca
openssl genrsa -out "$cert_dir/sa.key" 2048 2>/dev/null
openssl rsa -in "$cert_dir/sa.key" -pubout -out "$cert_dir/sa.pub" 2>/dev/null

ca_hash="sha256:$(openssl x509 -pubkey -in "$cert_dir/ca.crt" | openssl rsa -pubin -outform der 2>/dev/null | openssl dgst -sha256 -hex | sed 's/^.* //')"

header() {
  cat <<EOF
# Generated by scripts/generate-k8s-certs.sh -- contains cluster secrets, do not commit.
variant: flatcar
version: 1.1.0
storage:
  files:
EOF
}

# Emit one Butane file entry with the file contents indented under `inline: |`
entry() {
  printf '    - path: %s\n      mode: %s\n      contents:\n        inline: |\n' "$1" "$2"
  sed 's/^/          /' "$3"
}

{
  header
  entry /etc/kubernetes/pki/ca.crt 0644 "$cert_dir/ca.crt"
  entry /etc/kubernetes/pki/ca.key 0600 "$cert_dir/ca.key"
  entry /etc/kubernetes/pki/front-proxy-ca.crt 0644 "$cert_dir/front-proxy-ca.crt"
  entry /etc/kubernetes/pki/front-proxy-ca.key 0600 "$cert_dir/front-proxy-ca.key"
  entry /etc/kubernetes/pki/sa.key 0600 "$cert_dir/sa.key"
  entry /etc/kubernetes/pki/sa.pub 0644 "$cert_dir/sa.pub"
  entry /etc/kubernetes/pki/etcd/ca.crt 0644 "$cert_dir/etcd-ca.crt"
  entry /etc/kubernetes/pki/etcd/ca.key 0600 "$cert_dir/etcd-ca.key"
} > "$pki_yaml"

{
  header
  cat <<EOF
    - path: /etc/kubernetes/certs.conf
      mode: 0600
      contents:
        inline: |
          K8S_TOKEN=$token
          K8S_HASH=$ca_hash
EOF
} > "$token_yaml"

echo "Wrote $token_yaml and $pki_yaml (CA hash $ca_hash)"
