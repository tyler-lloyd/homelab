#!/usr/bin/env bash
# Print Butane configs with the cluster's addresses filled in, from nodes.conf
# and k8s/clusters/homelab/cluster.env. Nothing in butane/ names an address.
#
#   render-butane.sh layer <file>   a layer from butane/, with its @NAME@ placeholders replaced
#   render-butane.sh node <name>    the config for one node: hostname, network,
#                                   kubelet arguments and (control plane) keepalived

set -euo pipefail

cd "$(dirname "$0")/.."

# shellcheck source=../k8s/clusters/homelab/cluster.env
. k8s/clusters/homelab/cluster.env
: "${LAN_PREFIX_LEN:?}" "${LAN_GATEWAY:?}" "${DNS_SERVERS:?}" "${API_VIP:?}" "${POD_CIDR:?}" "${SERVICE_CIDR:?}"

# Control plane nodes in nodes.conf order, as parallel arrays
cp_names=() cp_ips=()
while read -r n r _ _ i _; do
  case $r in
    control-plane) cp_names+=("$n"); cp_ips+=("$i") ;;
    worker) ;;
    *) echo "nodes.conf: $n has role '$r'; expected control-plane or worker" >&2; exit 1 ;;
  esac
done < <(awk '!/^#/ && NF' nodes.conf)
if (( ${#cp_names[@]} == 0 )); then
  echo "nodes.conf: no control-plane node" >&2
  exit 1
fi

layer() {
  local file=$1 line out
  while IFS= read -r line; do
    # A line holding only this placeholder becomes one HAProxy server line
    # per control plane node, at the same indentation.
    if [[ $line =~ ^(\ *)@CONTROL_PLANE_SERVERS@$ ]]; then
      for i in "${!cp_names[@]}"; do
        printf '%sserver %s %s:6443\n' "${BASH_REMATCH[1]}" "${cp_names[i]}" "${cp_ips[i]}"
      done
      continue
    fi
    out=${line//@API_VIP@/$API_VIP}
    out=${out//@POD_CIDR@/$POD_CIDR}
    out=${out//@SERVICE_CIDR@/$SERVICE_CIDR}
    if [[ $out =~ @[A-Z_]+@ ]]; then
      echo "$file: unknown placeholder ${BASH_REMATCH[0]}" >&2
      exit 1
    fi
    printf '%s\n' "$out"
  done < "$file"
}

# One storage.files entry; the file's contents come from stdin
file() {
  printf '    - path: %s\n' "$1"
  [[ -z ${2:-} ]] || printf '      mode: %s\n' "$2"
  printf '      contents:\n        inline: |\n'
  sed 's/^\(.\)/          \1/'
}

node() {
  local name role ip gpu labels
  read -r name role _ _ ip _ _ _ gpu labels < <(awk -v n="$1" '!/^#/ && $1 == n' nodes.conf) || true
  if [[ ${name:-} != "$1" ]]; then
    echo "unknown node '$1' (see nodes.conf)" >&2
    exit 1
  fi
  gpu=${gpu:--}
  labels=${labels:--}

  # Position among the control plane nodes; stays -1 for a worker
  local index=-1 i
  for i in "${!cp_names[@]}"; do
    [[ ${cp_names[i]} != "$name" ]] || index=$i
  done

  # Which kubeadm layer the node boots with
  local base
  if (( index == 0 )); then
    base=30_base-ha-init
  elif (( index > 0 )); then
    base=31_base-ha-join-cp
  else
    base=32_base-ha-join
  fi

  local node_labels=()
  [[ $gpu == - ]] || node_labels+=(nvidia.com/gpu.present=true)
  [[ $labels == - ]] || node_labels+=("$labels")
  local kubelet_args="--node-ip=$ip"
  if (( ${#node_labels[@]} )); then
    kubelet_args+=" --node-labels=$(IFS=,; echo "${node_labels[*]}")"
  fi

  cat <<YAML
# Generated by scripts/render-butane.sh from nodes.conf and cluster.env
variant: flatcar
version: 1.1.0
ignition:
  config:
    merge:
      - local: ign/$base.ign
YAML
  [[ $gpu == - ]] || echo "      - local: ign/40_gpu-nvidia.ign"
  cat <<YAML
storage:
  files:
    - path: /etc/hostname
      overwrite: true
      contents:
        inline: $name
YAML

  file /etc/systemd/network/00-eth0.network <<CONF
[Match]
Name=eth0

[Network]
Address=$ip/$LAN_PREFIX_LEN
Gateway=$LAN_GATEWAY
$(printf 'DNS=%s\n' ${DNS_SERVERS//,/ })
CONF

  # A joining control plane node waits for the one listed before it, so they
  # join one at a time.
  local node_env="NODE_IP=$ip"
  (( index <= 0 )) || node_env+=$'\n'"WAIT_FOR_CP=${cp_ips[index-1]}"
  file /etc/kubernetes/node-env.conf <<< "$node_env"

  # Pin the node IP so the kubelet never picks up the keepalived VIP
  file /etc/sysconfig/kubelet <<CONF
KUBELET_EXTRA_ARGS=$kubelet_args
CONF

  (( index >= 0 )) || return 0

  # The first control plane node starts as the VIP's holder; the rest back it
  # up, in order.
  local peers=
  for i in "${!cp_names[@]}"; do
    (( i == index )) || peers+="        ${cp_ips[i]}"$'\n'
  done
  file /etc/keepalived/keepalived.conf 0644 <<CONF
global_defs {
    router_id $name
    enable_script_security
    script_user root
}
vrrp_script check_apiserver {
    # /etc is mounted noexec on Flatcar, so run curl directly rather than a script
    script "/usr/bin/curl -sfk --max-time 2 -o /dev/null https://127.0.0.1:6444/readyz"
    interval 3
    weight -2
    fall 10
    rise 2
}
vrrp_instance VI_1 {
    state $( (( index == 0 )) && echo MASTER || echo BACKUP )
    interface eth0
    virtual_router_id 51
    priority $(( 101 - index ))
    unicast_src_ip $ip
    unicast_peer {
${peers%$'\n'}
    }
    authentication {
        auth_type PASS
        auth_pass kubevip
    }
    virtual_ipaddress {
        $API_VIP/32
    }
    track_script {
        check_apiserver
    }
}
CONF
}

case ${1:-} in
  layer) layer "${2:?butane file required}" ;;
  node) node "${2:?node name required}" ;;
  *) sed -n '2,7p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 1 ;;
esac
